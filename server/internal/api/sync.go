package api

import (
	"log/slog"
	"net/http"
	"strconv"
	"time"

	"salio/server/internal/middleware"
	"salio/server/internal/models"
)

// SyncHandler handles the offline-first sync routes (Push and Pull).
type SyncHandler struct {
	syncRepo SyncRepository
}

// NewSyncHandler creates a new SyncHandler.
func NewSyncHandler(syncRepo SyncRepository) *SyncHandler {
	return &SyncHandler{syncRepo: syncRepo}
}

// Pull handles GET /v1/sync/pull
//
// Two modes, so a server upgrade does not break app versions already installed:
//
//	?cursor=<n>[&limit=<n>]  the correct path — a server-issued sequence cursor
//	?last_sync=<rfc3339>     legacy, retained for older clients
//	(no parameters)          first sync; treated as cursor 0
//
// The legacy path carries a defect that can permanently hide records from a
// device (see migration 006). It is kept only so existing installations continue
// to work unchanged until they update, and it is not fixable without the client
// also changing what it stores.
func (h *SyncHandler) Pull(w http.ResponseWriter, r *http.Request) {
	businessID := middleware.GetBusinessID(r.Context())

	cursorStr := r.URL.Query().Get("cursor")
	lastSyncStr := r.URL.Query().Get("last_sync")

	// An explicit cursor always wins. A client that understands cursors may still
	// send last_sync during a transition, and must not be dropped back onto the
	// broken path because it did.
	if cursorStr == "" && lastSyncStr != "" {
		lastSync, err := time.Parse(time.RFC3339, lastSyncStr)
		if err != nil {
			respondError(w, http.StatusBadRequest, ErrCodeValidation, "last_sync must be a valid RFC3339 timestamp")
			return
		}

		payload, err := h.syncRepo.Pull(r.Context(), businessID, lastSync)
		if err != nil {
			slog.Error("Legacy sync pull failed", "error", err, "business_id", businessID)
			respondError(w, http.StatusInternalServerError, ErrCodeInternal, "Failed to pull sync data")
			return
		}
		slog.Info("Legacy timestamp sync used", "business_id", businessID)
		respond(w, http.StatusOK, payload)
		return
	}

	var cursor int64
	if cursorStr != "" {
		parsed, err := strconv.ParseInt(cursorStr, 10, 64)
		if err != nil || parsed < 0 {
			respondError(w, http.StatusBadRequest, ErrCodeValidation, "cursor must be a non-negative integer")
			return
		}
		cursor = parsed
	}

	limit := 0
	if limitStr := r.URL.Query().Get("limit"); limitStr != "" {
		parsed, err := strconv.Atoi(limitStr)
		if err != nil || parsed <= 0 {
			respondError(w, http.StatusBadRequest, ErrCodeValidation, "limit must be a positive integer")
			return
		}
		limit = parsed
	}

	payload, err := h.syncRepo.PullByCursor(r.Context(), businessID, cursor, limit)
	if err != nil {
		slog.Error("Sync pull failed", "error", err, "business_id", businessID)
		respondError(w, http.StatusInternalServerError, ErrCodeInternal, "Failed to pull sync data")
		return
	}

	respond(w, http.StatusOK, payload)
}

// Push handles POST /v1/sync/push
// Receives batches of records from the mobile app and upserts them locally.
func (h *SyncHandler) Push(w http.ResponseWriter, r *http.Request) {
	businessID := middleware.GetBusinessID(r.Context())

	var payload models.SyncPayload
	if !decode(w, r, &payload) {
		return
	}

	// We trust the UUIDs generated by the client, but we enforce the business_id
	// at the database layer (in SyncRepository) to ensure tenants cannot overwrite each other.

	if err := h.syncRepo.Push(r.Context(), businessID, payload); err != nil {
		slog.Error("Sync Push failed", "error", err, "business_id", businessID)
		respondError(w, http.StatusInternalServerError, ErrCodeInternal, "Failed to push sync data: "+err.Error())
		return
	}

	respond(w, http.StatusOK, map[string]string{
		"message": "Sync successful",
	})
}
